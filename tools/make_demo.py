TTS_CACHE = os.path.join(tempfile.gettempdir(), "cqa_tts_cache")

# запасные голоса (говорят на многих языках), если основной не смог озвучить фразу
FALLBACK = {"ru-RU-DmitryNeural": "en-US-AndrewMultilingualNeural",
            "kk-KZ-DauletNeural": "en-US-AndrewMultilingualNeural",
            "ru-RU-SvetlanaNeural": "en-US-EmmaMultilingualNeural",
            "kk-KZ-AigulNeural": "en-US-EmmaMultilingualNeural"}


def tts(text, voice, path):
    """Озвучить фразу. Готовые фразы берём из кэша; сервис ограничивает частоту запросов,
    поэтому делаем паузы и несколько попыток."""
    os.makedirs(TTS_CACHE, exist_ok=True)
    cached = os.path.join(TTS_CACHE, hashlib.md5((voice + text).encode()).hexdigest() + ".mp3")
    for attempt in range(6):
        if attempt == 3 and voice in FALLBACK:
            voice = FALLBACK[voice]
        if os.path.exists(cached):
            shutil.copy(cached, path)
            return
        result = subprocess.run(["python3", "-m", "edge_tts", "--voice", voice, "--text", text,
                                 "--write-media", cached], capture_output=True, text=True)
        if result.returncode != 0 and os.path.exists(cached):
            os.remove(cached)
        time.sleep(1 if result.returncode == 0 else 5)
    raise RuntimeError("Не удалось озвучить: " + text + "\n" + result.stderr[-300:])


def build_call(item, set_dir, tmp):
    operator_voice, client_voice = VOICES[item["lang"]]
    if item.get("swap"):
        # другой пол голосов для разнообразия
        other = {"ru": ("ru-RU-DmitryNeural", "ru-RU-SvetlanaNeural"),
                 "kk": ("kk-KZ-DauletNeural", "kk-KZ-AigulNeural"),
                 "en": ("en-US-AndrewNeural", "en-US-JennyNeural")}
        operator_voice, client_voice = other[item["lang"]]
    rate = 24000
    t = 0.5
    pieces, turns = [], []
    for i, (role, text) in enumerate(item["turns"]):
        if role == "e":
            turns.append({"speaker": "system", "text": text, "start": round(t, 2), "end": round(t, 2)})
            continue
        mp3 = os.path.join(tmp, "%s_%d.mp3" % (item["id"], i))
        wav = os.path.join(tmp, "%s_%d.wav" % (item["id"], i))
        tts(text, operator_voice if role == "o" else client_voice, mp3)
        subprocess.run(["afconvert", "-f", "WAVE", "-d", "LEI16@%d" % rate, "-c", "1", mp3, wav], check=True)
        with wave.open(wav) as w:
            frames = w.readframes(w.getnframes())
            duration = w.getnframes() / w.getframerate()
        turns.append({"speaker": ROLE[role], "text": text, "start": round(t, 2), "end": round(t + duration, 2)})
        pieces.append((t, frames))
        t += duration + 0.6
    buf = bytearray(int((t + 0.5) * rate) * 2)
    for start, frames in pieces:
        offset = int(start * rate) * 2
        buf[offset:offset + len(frames)] = frames
    full = os.path.join(tmp, item["id"] + ".wav")
    with wave.open(full, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(bytes(buf))
    os.makedirs(os.path.join(set_dir, "audio"), exist_ok=True)
    m4a = os.path.join(set_dir, "audio", item["id"] + ".m4a")
    subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "64000", full, m4a], check=True)
    return {"conversation_id": item["id"], "channel": "call", "language": item["lang"],
            "audio_url": m4a, "transcript": turns}


def build_chat(item):
    messages, sec = [], 0
    for role, text, gap in item["turns"]:
        sec += gap
        messages.append({"role": ROLE[role], "text": text,
                         "timestamp": "2026-10-15T10:%02d:%02d" % (sec // 60 % 60, sec % 60)})
    return {"conversation_id": item["id"], "channel": "chat", "language": item["lang"], "messages": messages}


def build_set(name, items):
    set_dir = os.path.join("data", name)
    if os.path.isdir(set_dir):
        shutil.rmtree(set_dir)
    os.makedirs(set_dir)
    tmp = tempfile.mkdtemp()
    dialogs, cache = [], {}
    for item in items:
        print("  ", item["id"])
        dialogs.append(build_call(item, set_dir, tmp) if item["channel"] == "call" else build_chat(item))
        cache[item["id"]] = {"answer": item["eval"], "model": MODEL_NAME}
    with open(os.path.join(set_dir, "dialogs.json"), "w", encoding="utf-8") as f:
        json.dump(dialogs, f, ensure_ascii=False, indent=2)
    os.makedirs("cache", exist_ok=True)
    with open(os.path.join("cache", name + ".json"), "w", encoding="utf-8") as f:
        json.dump(cache, f, ensure_ascii=False, indent=2)
    shutil.rmtree(tmp)


