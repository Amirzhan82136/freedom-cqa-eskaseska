# Роли: o - оператор, c - клиент, b - бот, e - событие
ROLE = {"o": "operator", "c": "client", "b": "bot", "e": "system"}


def chat(cid, lang, turns, evaluation):
    return {"id": cid, "channel": "chat", "lang": lang, "turns": turns, "eval": evaluation}


def call(cid, lang, turns, evaluation, swap_voices=False):
    return {"id": cid, "channel": "call", "lang": lang, "turns": turns, "eval": evaluation, "swap": swap_voices}


def ev(contact, discovery, identification, consultation, empathy, dialogue, closure, critical):
    """Каждый аргумент: (значение, объяснение, [номера реплик])."""
    ids = ["contact", "discovery", "identification", "consultation", "empathy", "dialogue", "closure", "critical"]
    items = [contact, discovery, identification, consultation, empathy, dialogue, closure, critical]
    return {i: {"rationale": r, "value": v, "evidence_turns": t} for i, (v, r, t) in zip(ids, items)}


